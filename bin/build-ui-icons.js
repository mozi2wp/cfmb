function toPhp( map ) {
	return 'array(\n' + Object.entries( map ).map( ( [ k, v ] ) => `\t'${ k }' => '${ v.replace( /\\\\/g, '\\\\\\\\' ).replace( /'/g, "\\\\'" ) }',` ).join( '\n' ) + '\n)';
}

